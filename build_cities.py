# ---------------------------------------------------------------- GCJ-02 -> WGS-84
_PI = 3.1415926535897932384626
_A = 6378245.0
_EE = 0.00669342162296594323


def _tf_lat(x, y):
    r = -100 + 2 * x + 3 * y + 0.2 * y * y + 0.1 * x * y + 0.2 * (abs(x) ** 0.5)
    r += (20 * __import__("math").sin(6 * x * _PI) + 20 * __import__("math").sin(2 * x * _PI)) * 2 / 3
    r += (20 * __import__("math").sin(y * _PI) + 40 * __import__("math").sin(y / 3 * _PI)) * 2 / 3
    r += (160 * __import__("math").sin(y / 12 * _PI) + 320 * __import__("math").sin(y * _PI / 30)) * 2 / 3
    return r


def _tf_lng(x, y):
    import math
    r = 300 + x + 2 * y + 0.1 * x * x + 0.1 * x * y + 0.1 * (abs(x) ** 0.5)
    r += (20 * math.sin(6 * x * _PI) + 20 * math.sin(2 * x * _PI)) * 2 / 3
    r += (20 * math.sin(x * _PI) + 40 * math.sin(x / 3 * _PI)) * 2 / 3
    r += (150 * math.sin(x / 12 * _PI) + 300 * math.sin(x / 30 * _PI)) * 2 / 3
    return r


def gcj2wgs(lat, lng):
    """GCJ-02 -> WGS-84（迭代两次，误差 <1m）。"""
    import math
    wlat, wlng = lat, lng
    for _ in range(3):
        dlat = _tf_lat(wlng - 105.0, wlat - 35.0)
        dlng = _tf_lng(wlng - 105.0, wlat - 35.0)
        rad = wlat / 180 * _PI
        m = 1 - _EE * math.sin(rad) ** 2
        sq = math.sqrt(m)
        dlat = (dlat * 180) / ((_A * (1 - _EE)) / (m * sq) * _PI)
        dlng = (dlng * 180) / (_A / sq * math.cos(rad) * _PI)
        wlat, wlng = lat - dlat, lng - dlng
    return wlat, wlng


# ---------------------------------------------------------------- 三级站名匹配
def station_geo_match(name, geo):
    """StationGeo 同名站 / 同名+方位后缀（东/南/西/北/站）。返回 (lng, lat) 或 None。"""
    n = re.sub(r"\s+", "", name or "")
    pt = geo.get(n) or geo.get(name)
    if pt:
        return pt
    for suf in ("东", "南", "西", "北"):
        pt = geo.get(n + suf)
        if pt:
            return pt
    pt = geo.get(n + "站")
    return pt


# ---------------------------------------------------------------- 高德 / Nominatim
def amap_geocode(query, key):
    """高德地理编码（GCJ-02）→ (lat, lng, formatted) 或 None。"""
    url = ("https://restapi.amap.com/v3/geocode/geocode?address=%s&key=%s"
           % (urllib.parse.quote(query), key))
    try:
        with urllib.request.urlopen(url, timeout=20) as r:
            obj = json.loads(r.read().decode("utf-8"))
    except Exception as e:
        print("  amap %s 失败: %s" % (query, e))
        return None
    geo = (obj.get("geocodes") or [])
    if obj.get("status") != "1" or not geo:
        return None
    g = geo[0]
    loc = (g.get("location") or "").split(",")
    if len(loc) != 2:
        return None
    lng, lat = float(loc[0]), float(loc[1])
    wlat, wlng = gcj2wgs(lat, lng)
    return (wlat, wlng, g.get("formatted_address") or "",
            g.get("province") or "", g.get("city") or "")


def nominatim_geocode(query):
    url = ("https://nominatim.openstreetmap.org/search?format=json&limit=1&q=%s"
           % urllib.parse.quote(query + ", 中国"))
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "railmap-build-cities/1.0"})
        with urllib.request.urlopen(req, timeout=25) as r:
            arr = json.loads(r.read().decode("utf-8"))
    except Exception as e:
        print("  nominatim %s 失败: %s" % (query, e))
        return None
    if not arr:
        return None
    return (float(arr[0]["lat"]), float(arr[0]["lon"]), arr[0].get("display_name", ""), "", "")


